#!/usr/bin/env python3
"""Can a CuTe-DSL sm120 FP8 GEMM with the per-row/per-column scaled epilogue replace the two-pass path on GB10?

Kernel: scripts/cutlass_sm120_dsl_fp8_gemm.py, generated by scripts/cutlass_sm120_make_kernel.py from CUTLASS 4.7.1's CuTe-DSL Blackwell-GeForce dense GEMM
example (examples/python/CuTeDSL/cute/blackwell_geforce/kernel/dense_gemm/dense_gemm.py): TMA loads, one producer
warp + N MMA warps, warp-level mma.sync m16n8k32 e4m3 (cute.nvgpu.warp.MmaFP8Op), persistent tile scheduler with an
L2 swizzle; the epilogue applies y = sa[m] * (sb[n] * acc) in fp32 and rounds once to bf16 (h3_tp2.fp8_gemm's order;
the four DiT GEMMs have no bias).

Per shape and M it times, on the same inputs as scripts/fp8_epilogue_probe.py:
  ceil_bf16_scalar   cuBLASLt (torch._scaled_mm) scalar scales, bf16 out: the speed ceiling
  lt_fp32            cuBLASLt scalar scales, fp32 out (the GEMM half of the two-pass path)
  two_pass           h3_tp2.fp8_gemm.scaled_mm_tensor32 (serving's qkv/out/fc2 before item 6b; the reference)
  dsl_plain [cfg]    DSL kernel, no scales, bf16 out (comparable to the ceiling)
  dsl_scaled [cfg]   DSL kernel with the scaled epilogue, bf16 out: bitwise/ulp vs two_pass
  dsl_acc32 [cfg]    DSL kernel, raw fp32 accumulator: bitwise vs lt_fp32 (same reduction as cuBLASLt or not)

Usage (Spark_06, ~/h3-long/.venv/bin/python; the serving head may stay up: peak ~10 GB at M=42848 fc1):
  python scripts/cutlass_sm120_fp8_probe.py --m 21952 --shapes fc2 --cfgs "128,128,64,2,2,1,8,0,1" --jsonl out.jsonl
cfg = BM,BN,BK,atomM,atomN,atomK,swizzle,raster_along_m(0/1),epi_stage[,mma_regs]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("H3_TP2_REPO", os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(REPO, "scripts"))
sys.path.insert(0, REPO)
from fp8_epilogue_probe import SHAPES, bench, compare, make_inputs, verdict  # noqa: E402
from h3_tp2 import fp8_gemm  # noqa: E402

import cuda.bindings.driver as cuda  # noqa: E402
import cutlass  # noqa: E402
import cutlass.cute as cute  # noqa: E402
from cutlass.cute.runtime import from_dlpack  # noqa: E402

from cutlass_sm120_dsl_fp8_gemm import Sm120GemmKernel  # noqa: E402

E4M3 = torch.float8_e4m3fn
DEV = "cuda"


def cute_2d(t, dtype):
    """[R, C] row-major torch tensor -> cute tensor (R, C, 1), K/N-major, dynamic layout (one compile for all shapes)."""
    raw = t.view(torch.uint8) if t.dtype == E4M3 else t
    ct = from_dlpack(raw.unsqueeze(0).permute(1, 2, 0), assumed_align=16)
    ct.element_type = dtype
    return ct.mark_layout_dynamic(leading_dim=1)


def cute_1d(t):
    return from_dlpack(t, assumed_align=16).mark_layout_dynamic()


class DslGemm:
    def __init__(self, cfg, scaled, out_dtype):
        bm, bn, bk, am, an, ak, sw, ram, es = cfg[:9]
        regs = cfg[9] if len(cfg) > 9 else 232
        self.cfg = cfg
        self.bm = bm
        self.kernel = Sm120GemmKernel(cutlass.Float32, (bm, bn, bk), atom_layout=(am, an, ak), swizzle_size=sw,
                                      raster_along_m=bool(ram), epi_stage=es, scaled=scaled, mma_regs=regs)
        self.out_dtype = out_dtype
        self.cdt = {torch.bfloat16: cutlass.BFloat16, torch.float32: cutlass.Float32}[out_dtype]
        self.compiled = None
        self.stream = cuda.CUstream(torch.cuda.current_stream().cuda_stream)
        self.max_clusters = cutlass.utils.HardwareInfo().get_max_active_clusters(1)

    def prepare(self, a, w, sa, sb):
        """Bind one problem; returns a zero-argument launcher writing into a fresh output (scales padded to BM rows)."""
        M, N = a.shape[0], w.shape[0]
        bm, bn, sw, ram = self.cfg[0], self.cfg[1], self.cfg[6], self.cfg[7]
        tm, tn = -(-M // bm), -(-N // bn)
        if sw > 1:                                   # the scheduler rounds the swizzled grid dimension up
            if ram:
                tn = -(-tn // sw) * sw
            else:
                tm = -(-tm // sw) * sw
        sa_p = torch.ones(tm * bm, device=DEV, dtype=torch.float32)
        sa_p[:M] = sa.reshape(-1)
        sb_c = torch.ones(tn * bn, device=DEV, dtype=torch.float32)
        sb_c[:N] = sb.reshape(-1).float()
        # NaN-filled so an element the kernel never writes cannot pass as stale correct data from an earlier run
        out = torch.full((M, N), float("nan"), device=DEV, dtype=self.out_dtype)
        args = (cute_2d(a, cutlass.Float8E4M3FN), cute_2d(w, cutlass.Float8E4M3FN), cute_2d(out, self.cdt),
                cute_1d(sa_p), cute_1d(sb_c))
        if self.compiled is None:
            t0 = time.time()
            self.compiled = cute.compile(self.kernel, *args, self.max_clusters, self.stream)
            self.compile_s = time.time() - t0
        compiled, stream = self.compiled, self.stream

        def run():
            compiled(*args, stream)
            return out
        return run, out, (sa_p, sb_c)


def parse_cfgs(s):
    return [tuple(int(v) for v in c.split(",")) for c in s.split(";") if c.strip()]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--m", type=int, nargs="+", default=[21952])
    ap.add_argument("--shapes", nargs="+", default=list(SHAPES), choices=list(SHAPES))
    ap.add_argument("--inputs", default="random", choices=["random", "exact"])
    ap.add_argument("--cfgs", default="128,128,64,2,2,1,8,0,1")
    ap.add_argument("--iters", type=int, default=5)
    ap.add_argument("--variants", default="ceil,lt32,two_pass,plain,scaled,acc32")
    ap.add_argument("--jsonl", default="")
    args = ap.parse_args()
    want = set(args.variants.split(","))
    cfgs = parse_cfgs(args.cfgs)
    props = torch.cuda.get_device_properties(0)
    env = {"device": props.name, "cc": f"{props.major}.{props.minor}", "sms": props.multi_processor_count,
           "torch": torch.__version__, "cutlass_dsl": getattr(cutlass, "__version__", "?")}
    print(json.dumps(env), flush=True)
    fp8_gemm.probe_triton(DEV)
    one = torch.ones((), device=DEV, dtype=torch.float32)
    kernels = {}
    out_f = open(args.jsonl, "a") if args.jsonl else None

    def emit(r):
        r["time"] = time.strftime("%H:%M:%S")
        t = f"{r['ms_min']:8.3f} / {r['ms_med']:8.3f} ms {r['tflops']:6.1f} TF" if "ms_min" in r else " " * 36
        print(f"{r['shape']:4s} M={r['M']:6d} {r['variant']:44s} | {t} | {r.get('verdict', '')} {r.get('error', '')}",
              flush=True)
        if out_f:
            out_f.write(json.dumps(r) + "\n")
            out_f.flush()

    for M in args.m:
        for shape in args.shapes:
            N, K = SHAPES[shape]
            flop = 2.0 * M * N * K
            a, w, sa, sb = make_inputs(M, N, K, args.inputs, seed=sum(map(ord, shape)) * 100003 + M)
            wt = w.t()
            base = {"shape": shape, "M": M, "N": N, "K": K, "inputs": args.inputs}

            def timed(variant, fn, **extra):
                r = dict(base, variant=variant, **extra)
                try:
                    r["ms_min"], r["ms_med"] = bench(fn, args.iters)
                    r["tflops"] = flop / r["ms_min"] / 1e9
                except Exception as exc:  # noqa: BLE001
                    r["error"] = f"{type(exc).__name__}: {str(exc).splitlines()[0][:300] if str(exc) else ''}"
                emit(r)
                torch.cuda.empty_cache()
                return r

            if "ceil" in want:
                timed("ceil_bf16_scalar", lambda: torch._scaled_mm(a, wt, scale_a=one, scale_b=one, out_dtype=torch.bfloat16))
            if "lt32" in want:
                timed("lt_fp32", lambda: torch._scaled_mm(a, wt, scale_a=one, scale_b=one, out_dtype=torch.float32))
            if "two_pass" in want:
                timed("two_pass", lambda: fp8_gemm.scaled_mm_tensor32(a, wt, sa, sb, torch.bfloat16))
            ref = fp8_gemm.scaled_mm_tensor32(a, wt, sa, sb, torch.bfloat16) if "scaled" in want else None
            for cfg in cfgs:
                tag = ",".join(map(str, cfg))
                for kind in ("plain", "scaled", "acc32"):
                    if kind not in want:
                        continue
                    key = (cfg, kind)
                    r = dict(base, variant=f"dsl_{kind} [{tag}]", cfg=list(cfg))
                    try:
                        if key not in kernels:
                            kernels[key] = DslGemm(cfg, scaled=(kind == "scaled"),
                                                   out_dtype=torch.float32 if kind == "acc32" else torch.bfloat16)
                        g = kernels[key]
                        run, out, keep = g.prepare(a, w, sa, sb)
                        r["compile_s"] = round(getattr(g, "compile_s", 0.0), 1)
                        run()
                        torch.cuda.synchronize()
                        if kind == "scaled":
                            r["cmp"] = compare(out, ref)
                            r["verdict"] = verdict(r["cmp"])
                        elif kind == "acc32":
                            x32 = torch._scaled_mm(a, wt, scale_a=one, scale_b=one, out_dtype=torch.float32)
                            r["cmp"] = compare(out, x32)
                            r["verdict"] = "acc vs cuBLASLt fp32: " + verdict(r["cmp"])
                            del x32
                        else:
                            x = torch._scaled_mm(a, wt, scale_a=one, scale_b=one, out_dtype=torch.bfloat16)
                            c = compare(out, x)
                            r["cmp"] = c
                            r["verdict"] = "vs ceiling bf16: " + verdict(c)
                            del x
                        r["ms_min"], r["ms_med"] = bench(run, args.iters)
                        r["tflops"] = flop / r["ms_min"] / 1e9
                        del out, run, keep
                    except Exception as exc:  # noqa: BLE001
                        r["error"] = f"{type(exc).__name__}: {str(exc)[:600]}"
                        kernels.pop(key, None)
                    emit(r)
                    torch.cuda.empty_cache()
            a = w = wt = sa = sb = ref = None
            torch.cuda.empty_cache()
    if out_f:
        out_f.close()


if __name__ == "__main__":
    main()
